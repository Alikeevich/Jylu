"""
Jylu logo — generates every brand file from one geometry.

The wordmark is lowercase Kazakh Latin "jylu" (жылу, warmth), drawn as a
heating pipe: one stroke weight, straight runs, bends of one radius, flat
cut ends. The tittle of the j is a square "hot pixel" in ember: the warm
spot a thermal camera finds in a cold frame. Its top sits on the ascender line.

    python3 scripts/brand.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INK, SNOW, EMBER, PAPER, WHITE = "#0b0d14", "#eef0f5", "#ff6a2b", "#f4f6f9", "#ffffff"
GRAPHITE = "#111827"

# geometry, in units of a 100-unit x-height
W = 24          # stroke
R = 32          # bend radius (centerline)
XH = 100        # x-height
ASC = 140       # ascender (l and the hot pixel)
DESC = 40       # descender hook centerline below the baseline
O = 3           # overshoot of the bowls below the baseline
GAP = 32        # space between neighbouring stems
HOOK = 8        # straight run after the j and y bends
B = 130         # baseline


def n(v):
    v = round(v, 2)
    return str(int(v)) if v == int(v) else str(v)


def wordmark_geometry():
    T, A, D = B - XH, B - ASC, B + DESC
    yb = B + O - W / 2 - R              # stems turn into the bowl here
    step = W + GAP                      # stem-to-stem distance between letters
    j0 = R + HOOK                       # the j hook ends at x = 0
    y0 = j0 + step
    yr = y0 + 2 * R
    l0 = yr + step
    u0 = l0 + step
    ur = u0 + 2 * R
    d = (
        f"M{n(j0)} {n(T)}V{n(D - R)}A{R} {R} 0 0 1 {n(j0 - R)} {n(D)}H{n(j0 - R - HOOK)}"
        f"M{n(y0)} {n(T)}V{n(yb)}A{R} {R} 0 0 0 {n(yr)} {n(yb)}"
        f"M{n(yr)} {n(T)}V{n(D - R)}A{R} {R} 0 0 1 {n(yr - R)} {n(D)}H{n(yr - R - HOOK)}"
        f"M{n(l0)} {n(A)}V{n(B - W / 2 - R)}A{R} {R} 0 0 0 {n(l0 + R)} {n(B - W / 2)}"
        f"M{n(u0)} {n(T)}V{n(yb)}A{R} {R} 0 0 0 {n(ur)} {n(yb)}V{n(T)}"
    )
    pixel = (j0 - W / 2, A, W)
    box = (0, A, ur + W / 2, D + W / 2)
    j_only = f"M{n(j0)} {n(T)}V{n(D - R)}A{R} {R} 0 0 1 {n(j0 - R)} {n(D)}H{n(j0 - R - HOOK)}"
    return {"d": d, "pixel": pixel, "box": box, "j": j_only, "j0": j0, "A": A, "D": D}


G = wordmark_geometry()


def wordmark_svg(fg, accent, title="Jylu"):
    x0, y0, x1, y1 = G["box"]
    px, py, ps = G["pixel"]
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{n(x0)} {n(y0)} {n(x1 - x0)} {n(y1 - y0)}" role="img" aria-label="{title}">'
        f"<title>{title}</title>"
        f'<path d="{G["d"]}" fill="none" stroke="{fg}" stroke-width="{W}"/>'
        f'<rect x="{n(px)}" y="{n(py)}" width="{ps}" height="{ps}" fill="{accent}"/></svg>\n'
    )


def icon_svg(fg, accent, bg, size=512, radius=112, weight=34, fill=0.7, square=False):
    """The j with its hot pixel. Heavier stroke so it holds at 16-32 px."""
    r, hook, w = 30, 6, weight
    T, D = B - XH, B + DESC
    A = T - 18 - w                      # keep the pixel clear of the heavier stem
    j0 = r + hook
    path = f"M{n(j0)} {n(T)}V{n(D - r)}A{r} {r} 0 0 1 {n(j0 - r)} {n(D)}H{n(j0 - r - hook)}"
    gx0, gx1 = 0, j0 + w / 2
    gy0, gy1 = A, D + w / 2
    s = size * fill / (gy1 - gy0)
    # centre the glyph's mass: the stem and pixel, not the hook, carry it
    cx = (j0 + gx0 + gx1) / 3
    tx = size / 2 - cx * s
    ty = size / 2 - (gy0 + gy1) / 2 * s
    rx = 0 if square else radius
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {size} {size}">'
        f'<rect width="{size}" height="{size}" rx="{rx}" fill="{bg}"/>'
        f'<g transform="translate({n(tx)} {n(ty)}) scale({s:.5f})">'
        f'<path d="{path}" fill="none" stroke="{fg}" stroke-width="{w}"/>'
        f'<rect x="{n(j0 - w / 2)}" y="{n(A)}" width="{w}" height="{w}" fill="{accent}"/></g></svg>\n'
    )


def write(path, text):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    print("wrote", path)


def logo_component():
    x0, y0, x1, y1 = G["box"]
    px, py, ps = G["pixel"]
    return f'''/**
 * The Jylu wordmark. Generated by scripts/brand.py, do not edit by hand.
 * Letters take currentColor; the hot pixel over the j is always ember.
 */
export default function Logo({{ className, title = "Jylu" }}: {{ className?: string; title?: string }}) {{
  return (
    <svg
      className={{className}}
      viewBox="{n(x0)} {n(y0)} {n(x1 - x0)} {n(y1 - y0)}"
      role="img"
      aria-label={{title}}
    >
      <path d="{G["d"]}" fill="none" stroke="currentColor" strokeWidth={{{W}}} />
      <rect x="{n(px)}" y="{n(py)}" width="{ps}" height="{ps}" fill="var(--ember)" />
    </svg>
  );
}}
'''


if __name__ == "__main__":
    write("public/brand/jylu-wordmark-on-dark.svg", wordmark_svg(SNOW, EMBER))
    write("public/brand/jylu-wordmark-on-light.svg", wordmark_svg(GRAPHITE, EMBER))
    write("public/brand/jylu-wordmark-black.svg", wordmark_svg("#000000", "#000000"))
    write("public/brand/jylu-wordmark-white.svg", wordmark_svg("#ffffff", "#ffffff"))
    write("public/brand/jylu-icon.svg", icon_svg(SNOW, EMBER, INK))
    write("public/brand/jylu-icon-light.svg", icon_svg(GRAPHITE, EMBER, WHITE))
    write("app/icon.svg", icon_svg(SNOW, EMBER, INK))
    write("public/brand/jylu-icon-square.svg", icon_svg(SNOW, EMBER, INK, square=True))
    write("components/Logo.tsx", logo_component())
